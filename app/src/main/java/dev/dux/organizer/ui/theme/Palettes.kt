/**
 * The colors the user can pick in Ajustes. [Wallpaper] is Android's Dynamic Color; the fixed ones were
 * generated once from a seed with Material's own algorithm (material-color-utilities, tonal spot), the
 * same one Dynamic Color uses, so they behave like it in both light and dark.
 */
enum class Palette(@StringRes val label: Int, val swatch: Color, val light: ColorScheme?, val dark: ColorScheme?) {
    Wallpaper(R.string.palette_wallpaper, Color.Unspecified, null, null),
    Blue(R.string.palette_blue, Color(0xFF3D6FD8), blueLight, blueDark),
    Green(R.string.palette_green, Color(0xFF2E8B57), greenLight, greenDark),
    Purple(R.string.palette_purple, Color(0xFF7B4FC9), purpleLight, purpleDark),
    Orange(R.string.palette_orange, Color(0xFFE07B24), orangeLight, orangeDark),
    Pink(R.string.palette_pink, Color(0xFFD6447F), pinkLight, pinkDark),
}

